create or replace function public.log_truck_gps_health()
 returns integer
 language plpgsql
 set search_path to ''
as $function$
declare
  n integer;
  v_items jsonb;
  v_t0 timestamptz := clock_timestamp();
  v_today date := (now() at time zone 'America/New_York')::date;
begin
  -- the nightly rule's own evidence, dry run: pg_temp._veh_evidence(visit_id, stored_vehicle, filed, holders, holder)
  perform public.fn_infer_visit_vehicle(date '2026-08-20', v_today + 1, false);
  with m as (
    select e.visit_id, e.stored_vehicle, e.holder, e.filed, v.visit_date, v.client_id
      from pg_temp._veh_evidence e
      join public.visits v on v.id = e.visit_id
     where e.stored_vehicle is not null and e.holder is not null and e.holder <> e.stored_vehicle
       -- the nightly corrects an unfiled visit of its last 10 days by itself: only what it leaves is listed
       and (e.filed or v.visit_date < v_today - 9)
       -- a truck the 2026-10-18 duration fix set is a decision, not a gap
       and not exists (select 1 from public.visit_time_on_site_corrections x
                         where x.visit_id = e.visit_id and x.superseded_at is null and x.status = 'applied'
                           and x.new_vehicle_id = e.stored_vehicle)
       and not public.fn_is_non_customer(v.client_id)
  ), items as (
    select jsonb_build_object(
             'kind', 'truck_gps:v' || m.visit_id,
             'issue', 'truck_gps_differs',
             'visit', m.visit_id,
             'client_code', c.client_code,
             'reason', format('Visit %s (%s %s, %s) is on %s, but %s was the only truck parked there when it was marked done.%s',
                              m.visit_id, c.client_code, c.name, to_char(m.visit_date, 'Mon FMDD'), sv.name, hv.name,
                              case when m.filed then ' It is filed on a DERM manifest, so the nightly truck correction leaves it to a person.'
                                   else ' It is older than the 10 days the nightly truck correction looks at.' end),
             'what_to_do', format('Open %s and %s in Samsara at that time. If %s did the job, change the truck on the visit to %s (Viktor can do it from Slack; a truck change is not sent to Jobber). If %s is right, acknowledge this item (public.fn_health_ack) so it stops coming back.',
                                  sv.name, hv.name, hv.name, hv.name, sv.name),
             'stored_truck', sv.name, 'gps_truck', hv.name, 'filed', m.filed) as item
      from m
      join public.clients c on c.id = m.client_id
      join public.vehicles sv on sv.id = m.stored_vehicle
      join public.vehicles hv on hv.id = m.holder
  )
  select count(*), coalesce(jsonb_agg(item order by item->>'kind'), '[]'::jsonb) into n, v_items from items;

  insert into public.sync_log (sync_source, started_at, finished_at, rows_errored, status, details)
  values ('truck-gps-health', v_t0, clock_timestamp(), n,
          case when n > 0 then 'attention' else 'ok' end,
          jsonb_build_object('count', n, 'items', v_items, 'window_from', '2026-08-20'));
  return n;
end $function$;

revoke all on function public.log_truck_gps_health() from public, anon, authenticated;

CREATE OR REPLACE VIEW ops.v_health_items AS
 WITH latest AS (
         SELECT DISTINCT ON (l.sync_source) l.sync_source,
            l.status,
            l.started_at,
            l.details
           FROM sync_log l
          WHERE l.sync_source = ANY (ARRAY['calendar-push-health'::text, 'blackout-health'::text, 'rpa-derm-health'::text, 'sa-schedule-gap-check'::text, 'jobber-sync-health'::text, 'note-photo-sync-health'::text, 'jobber-client-state-sweep'::text, 'start-flags-health'::text, 'db-backup-health'::text, 'notification-health'::text, 'samsara-feed-health'::text, 'hr-bonus-health'::text, 'trap-size-health'::text, 'access-health'::text, 'truck-gps-health'::text])
          ORDER BY l.sync_source, l.started_at DESC
        )
